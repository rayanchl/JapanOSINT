describe('client layer definitions (clientOnly fallback allow-list)', () => {
  it('has no definition outside the allow-list', () => {
    const unlisted = Object.keys(LAYER_DEFINITIONS).filter((k) => !ALLOWED_CLIENT_LAYER_DEFINITIONS.includes(k));
    expect(unlisted).toEqual([]);
  });
  it('allow-list has no stale names (deleted definitions leave the list)', () => {
    const stale = ALLOWED_CLIENT_LAYER_DEFINITIONS.filter((k) => !(k in LAYER_DEFINITIONS));
    expect(stale).toEqual([]);
  });
  it('without a server catalogue every definition is clientOnly — the fallback itself still works', () => {
    const cat = buildCatalog([], LAYER_DEFINITIONS);
    const only = Object.keys(cat).filter((k) => cat[k].clientOnly && LAYER_DEFINITIONS[k]);
    expect(only.sort()).toEqual([...ALLOWED_CLIENT_LAYER_DEFINITIONS].sort());
  });
  it('a definition the server also declares is NOT clientOnly (so only genuinely local ones need listing)', () => {
    const first = Object.entries(LAYER_DEFINITIONS)[0];
    const slug = String(first[1].endpoint).split('/').filter(Boolean).pop();
    const cat = buildCatalog([{ id: slug, name: 'x', category: 'x' }], { [first[0]]: first[1] });
    expect(cat[first[0]].clientOnly).toBe(false);
  });
});

import { loadProgress } from '../layerCatalog.js';

describe('loadProgress (WEB-10)', () => {
  it('states N of M while pages are still arriving, and nothing once done', () => {
    const fc = { features: [{}, {}], _meta: { client_loading: true, records_used: 5000, records_available: 123456, pages: 1 } };
    expect(loadProgress(fc)).toBe('Loading 5,000 of 123,456 records (page 1)');
    expect(loadProgress({ features: [], _meta: { client_loading: true, records_available: null, records_used: 0 } })).toMatch(/unreported total/);
    expect(loadProgress({ features: [], _meta: { records_used: 5 } })).toBeNull();
  });
});
